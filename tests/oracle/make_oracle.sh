#!/bin/sh
# Regenerate legacy.sql: the materialized load + rollup SQL at commit 12ff764, moved into the
# gridtiles_oracle schema. Live tiles are tested against it (tests/sql/test_oracle.py).
set -eu
cd "$(dirname "$0")"
COMMIT=12ff764
{
    echo "-- Test-only oracle: the materialized load + rollup path at $COMMIT, in the schema"
    echo "-- gridtiles_oracle. Generated by make_oracle.sh; do not edit."
    for f in 001_schema 010_quadkey 020_layers 025_ingest 030_rollup 040_mvt; do
        echo
        echo "-- $f.sql"
        git show "$COMMIT:src/gridtiles/sql/$f.sql" | grep -v '^create extension' |
            sed -e 's/\bgridtiles\./gridtiles_oracle./g' \
                -e 's/create schema if not exists gridtiles;/create schema if not exists gridtiles_oracle;/'
    done
} > legacy.sql
